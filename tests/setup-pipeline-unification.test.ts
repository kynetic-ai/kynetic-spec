/**
 * Tests for Setup Pipeline Unification
 *
 * AC: @setup-pipeline-unification ac-1 through ac-5
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { execSync } from 'node:child_process';
import {
  kspec,
  createTempDir,
  cleanupTempDir,
  initGitRepo,
} from './helpers/cli.js';
import { SHADOW_WORKTREE_DIR } from '../src/parser/shadow.js';

/**
 * Helper: Set up a temp directory with git, kspec init, and a skill for rendering.
 */
async function setupKspecProject(tempDir: string): Promise<void> {
  initGitRepo(tempDir);
  await fs.writeFile(path.join(tempDir, 'README.md'), '# Test', 'utf-8');
  execSync('git add README.md && git commit -m "Initial"', {
    cwd: tempDir,
    stdio: 'pipe',
  });

  // Init kspec project
  const initResult = kspec('init --no-prompt', tempDir, {
    env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
  });
  expect(initResult.exitCode).toBe(0);
}

describe('Setup Pipeline Unification', () => {
  let tempDir: string;

  beforeEach(async () => {
    tempDir = await createTempDir('kspec-setup-unification-');
  });

  afterEach(async () => {
    await cleanupTempDir(tempDir);
  });

  // AC: @setup-pipeline-unification ac-1
  // Given: setup.ts needs to generate agent instructions
  // When: the setup pipeline runs
  // Then: it calls the exported generateAgentsContent() from agents.ts (not a local reimplementation)
  describe('ac-1: uses generateAgentsContent from agents.ts', () => {
    it('should produce identical kspec-agents.md from setup and agents generate', async () => {
      await setupKspecProject(tempDir);

      // Run setup (which generates kspec-agents.md via the pipeline)
      const setupResult = kspec('setup --dry-run', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(setupResult.exitCode).toBe(0);

      // Now run agents generate to get its output
      const agentsResult = kspec('agents generate', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(agentsResult.exitCode).toBe(0);

      // Verify the file was generated
      const agentsMdPath = path.join(tempDir, 'kspec-agents.md');
      const content = await fs.readFile(agentsMdPath, 'utf-8');
      // Both should produce a file with the same structural elements
      expect(content).toContain('# kspec Agent Instructions');
      expect(content).toContain('Generated by kspec');
    });

    it('should generate hash using computeMetaHash from agents.ts', async () => {
      await setupKspecProject(tempDir);

      // Run setup
      kspec('setup', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });

      // Verify hash file exists
      const hashPath = path.join(tempDir, '.kspec', '.kspec-agents-hash');
      const hashContent = await fs.readFile(hashPath, 'utf-8');
      const hashData = JSON.parse(hashContent);
      expect(hashData).toHaveProperty('metaHash');
      expect(hashData).toHaveProperty('generatedAt');
      expect(hashData).toHaveProperty('version');
      // metaHash should be a hex string (SHA256)
      expect(hashData.metaHash).toMatch(/^[a-f0-9]{64}$/);
    });
  });

  // AC: @setup-pipeline-unification ac-2
  // Given: setup.ts needs to render skills
  // When: the setup pipeline renders skills for any platform
  // Then: it uses the platform renderer registry (getRenderer/getAllRenderers) not the legacy renderClaudeCodeSkill
  describe('ac-2: uses platform renderer registry', () => {
    it('should render skills via the renderer registry', async () => {
      await setupKspecProject(tempDir);

      // Run setup which should render skills
      const result = kspec('setup', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);

      // Check that skills were rendered (the pipeline summary shows the count)
      expect(result.stdout).toContain('Render skills');
    });

    it('should render skills for all platforms with registered renderers', async () => {
      await setupKspecProject(tempDir);

      // Run setup
      const result = kspec('setup', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);

      // The rendered skills directory should exist
      const skillsDir = path.join(tempDir, '.claude', 'skills');
      try {
        const entries = await fs.readdir(skillsDir, { withFileTypes: true });
        const skillDirs = entries.filter(e => e.isDirectory());
        // If skills were rendered, each should have SKILL.md with kspec-managed marker
        for (const dir of skillDirs) {
          const skillMd = path.join(skillsDir, dir.name, 'SKILL.md');
          try {
            const content = await fs.readFile(skillMd, 'utf-8');
            expect(content).toContain('<!-- kspec-managed -->');
          } catch {
            // Some skill directories might not have SKILL.md
          }
        }
      } catch {
        // Skills dir might not exist if no skills are in meta
      }
    });
  });

  // AC: @setup-pipeline-unification ac-3
  // Given: the setup command is invoked
  // When: the command handler executes
  // Then: it delegates to runSetupPipeline() - there is one code path, not two parallel implementations
  describe('ac-3: single code path via runSetupPipeline', () => {
    it('should produce consistent output structure from setup command', async () => {
      await setupKspecProject(tempDir);

      // Run setup and verify it goes through the pipeline
      const result = kspec('setup --dry-run', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);

      // The output should include all pipeline steps
      expect(result.stdout).toContain('Agent detection');
      expect(result.stdout).toContain('Install core skills');
      expect(result.stdout).toContain('Render skills');
      expect(result.stdout).toContain('Generate kspec-agents.md');
    });

    it('should include author configuration when called from setup command', async () => {
      await setupKspecProject(tempDir);

      // Run setup with explicit author
      const result = kspec('setup --dry-run --author @myauthor --force', tempDir, {
        env: { CLAUDECODE: '1' },
      });
      expect(result.exitCode).toBe(0);

      // Should show Configure author step
      expect(result.stdout).toContain('Configure author');
      expect(result.stdout).toContain('@myauthor');
    });

    it('should handle --no-hooks through the unified pipeline', async () => {
      await setupKspecProject(tempDir);

      const result = kspec('setup --dry-run --no-hooks', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);

      expect(result.stdout).toContain('Install hooks');
      expect(result.stdout).toContain('skipped');
      expect(result.stdout).toContain('--no-hooks flag');
    });

    it('should handle --skip-skills through the unified pipeline', async () => {
      await setupKspecProject(tempDir);

      const result = kspec('setup --dry-run --skip-skills', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);

      expect(result.stdout).toContain('Render skills');
      expect(result.stdout).toContain('skipped');
      expect(result.stdout).toContain('--skip-skills flag');
    });
  });

  // AC: @setup-pipeline-unification ac-4
  // Given: any setup step throws an error
  // When: a catch block handles it
  // Then: the error is logged at debug level (not silently swallowed with bare catch {})
  describe('ac-4: errors logged at debug level', () => {
    it('should log errors when KSPEC_DEBUG is enabled', async () => {
      await setupKspecProject(tempDir);

      // Run setup with debug mode on a valid project - no errors expected
      const result = kspec('setup', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test', KSPEC_DEBUG: '1' },
      });
      expect(result.exitCode).toBe(0);
      // Debug output goes to stderr
      // In a healthy project, there may or may not be debug messages
      // The key assertion is that the code COMPILES without bare catch {}
    });

    it('should not produce debug output when KSPEC_DEBUG is not set', async () => {
      await setupKspecProject(tempDir);

      const result = kspec('setup', tempDir, {
        env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
      });
      expect(result.exitCode).toBe(0);
      // stderr should not contain debug messages
      expect(result.stderr).not.toContain('[DEBUG] setup:');
    });

    it('source code should have no bare catch blocks', async () => {
      // Static analysis: verify setup.ts has no bare catch {} blocks
      const setupTsPath = path.join(process.cwd(), 'src', 'cli', 'commands', 'setup.ts');
      const content = await fs.readFile(setupTsPath, 'utf-8');

      // Find catch blocks - bare catch {} means "catch {" without a variable binding
      // The pattern: catch followed by { without (err) or (e) or similar
      const bareCatchPattern = /\bcatch\s*\{/g;
      const matches = content.match(bareCatchPattern);

      expect(matches).toBeNull();
    });
  });

  // AC: @setup-pipeline-unification ac-5
  // Given: a new project runs kspec init --setup
  // When: setup completes
  // Then: the output is identical to running kspec setup separately (same code path)
  describe('ac-5: init --setup uses same code path as setup', () => {
    it('should produce the same artifacts from init --setup and setup separately', async () => {
      // Create two temp dirs for comparison
      const initDir = await createTempDir('kspec-init-setup-');
      const setupDir = await createTempDir('kspec-setup-only-');

      try {
        // Set up both directories
        for (const dir of [initDir, setupDir]) {
          initGitRepo(dir);
          await fs.writeFile(path.join(dir, 'README.md'), '# Test', 'utf-8');
          execSync('git add README.md && git commit -m "Initial"', {
            cwd: dir,
            stdio: 'pipe',
          });
        }

        // Path 1: kspec init --setup (single command)
        const initResult = kspec('init --no-prompt --setup', initDir, {
          env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
        });
        expect(initResult.exitCode).toBe(0);

        // Path 2: kspec init + kspec setup (two commands)
        const initOnly = kspec('init --no-prompt', setupDir, {
          env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
        });
        expect(initOnly.exitCode).toBe(0);

        const setupOnly = kspec('setup', setupDir, {
          env: { CLAUDECODE: '1', KSPEC_AUTHOR: '@test' },
        });
        expect(setupOnly.exitCode).toBe(0);

        // Both should produce kspec-agents.md
        const initAgentsMd = path.join(initDir, 'kspec-agents.md');
        const setupAgentsMd = path.join(setupDir, 'kspec-agents.md');

        const initContent = await fs.readFile(initAgentsMd, 'utf-8');
        const setupContent = await fs.readFile(setupAgentsMd, 'utf-8');

        // Both should have the same structure (timestamps will differ)
        expect(initContent).toContain('# kspec Agent Instructions');
        expect(setupContent).toContain('# kspec Agent Instructions');
        expect(initContent).toContain('Generated by kspec');
        expect(setupContent).toContain('Generated by kspec');

        // Both should have hooks installed
        const initHooksConfig = path.join(initDir, '.claude', 'settings.json');
        const setupHooksConfig = path.join(setupDir, '.claude', 'settings.json');

        const initHooks = JSON.parse(await fs.readFile(initHooksConfig, 'utf-8'));
        const setupHooks = JSON.parse(await fs.readFile(setupHooksConfig, 'utf-8'));

        // Both should have the same hook types
        expect(Object.keys(initHooks.hooks || {}).sort()).toEqual(
          Object.keys(setupHooks.hooks || {}).sort()
        );
      } finally {
        await cleanupTempDir(initDir);
        await cleanupTempDir(setupDir);
      }
    });
  });
});
